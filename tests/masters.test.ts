import {test} from 'node:test';
import assert from 'node:assert/strict';
import {Hono} from 'hono';
import {database} from './sqlite-helper';
import {scopedRoutes} from '../src/server/index';
import {businessClock,isWorkingInstant,workingMinutesBetween} from '../src/server/calendar';
test('master mutations enforce role, tenant, payload, ETag, idempotency and audit',async()=>{
 const {sqlite,adapter}=database();
 sqlite.exec("INSERT INTO organization(id,name,timezone) VALUES('o','Org','Asia/Jakarta'),('other','Other','Asia/Jakarta');INSERT INTO app_user(id,organization_id,name) VALUES('mg','o','MG'),('am','o','AM');INSERT INTO area(id,organization_id,name) VALUES('a','o','Area A'),('b','o','Area B');INSERT INTO user_area_scope VALUES('o','am','a','2020-01-01',NULL);");
 const req=(method:string,path:string,body?:object,role='MANAGEMENT',version?:number,key=crypto.randomUUID())=>{
  const h=new Hono();h.use('*',async(c,next)=>{c.set('identity' as never,{id:role==='MANAGEMENT'?'mg':'am',name:role,organization_id:'o',role} as never);await next()});h.route('/',scopedRoutes);
  return h.request(path,{method,headers:{'Content-Type':'application/json','Idempotency-Key':key,...(version?{'If-Match':`"${version}"`}:{})},...(body?{body:JSON.stringify(body)}:{})},{DB:adapter});
 };
 assert.equal((await req('POST','/api/branches',{name:'X',timezone:'Asia/Jakarta'},'AREA_MANAGER')).status,403);
 assert.equal((await req('POST','/api/branches',{name:'X',timezone:'Bad/Timezone'})).status,422);
 assert.equal((await req('POST','/api/branches',{name:'X',timezone:'Asia/Jakarta',organization_id:'other'})).status,422);
 const key=crypto.randomUUID(),input={name:'Cabang Timur',timezone:'Asia/Makassar'};
 const result=await req('POST','/api/branches',input,'MANAGEMENT',undefined,key);assert.equal(result.status,201);const created=await result.json() as any;const id=created.data.id;
 const replay=await req('POST','/api/branches',input,'MANAGEMENT',undefined,key);assert.equal((await replay.json() as any).data.id,id);
 assert.equal((await req('POST','/api/branches',{...input,name:'Berubah'},'MANAGEMENT',undefined,key)).status,409);
 assert.equal(sqlite.prepare('SELECT COUNT(*) n FROM master_audit').get()!.n,1);
 assert.equal((await req('PUT','/api/branches/'+id,input)).status,428);
 assert.equal((await req('PUT','/api/branches/'+id,input,'MANAGEMENT',9)).status,412);
 assert.equal((await req('PUT','/api/branches/'+id,{...input,name:'Cabang Utama'},'MANAGEMENT',1)).status,200);
 assert.equal((await req('PUT','/api/branches/'+id,input,'MANAGEMENT',1)).status,412);
 const area=await req('POST','/api/areas',{name:'Area Timur',branch_id:id});assert.equal(area.status,201);
 const areaId=(await area.json() as any).data.id;
 assert.equal((await req('POST','/api/areas',{name:'Other',branch_id:'foreign'})).status,422);
 sqlite.prepare('UPDATE area SET branch_id=? WHERE id=?').run(id,'a');
 assert.equal((await (await req('GET','/api/areas',undefined,'AREA_MANAGER')).json() as any).data.length,1);
 assert.equal((await req('GET','/api/areas/'+areaId,undefined,'AREA_MANAGER')).status,404);
 const calendar={name:'Standar',branch_id:id,weekdays:[1,2,3,4,5],start_time:'08:00',end_time:'17:00',holidays:['2026-12-25']};
 assert.equal((await req('POST','/api/calendars',{...calendar,holidays:['2026-02-30']})).status,422);
 assert.equal((await req('POST','/api/calendars',{...calendar,end_time:'07:00'})).status,422);
 assert.equal((await req('POST','/api/calendars',{...calendar,weekdays:[1,1]})).status,422);
 const cal=await req('POST','/api/calendars',calendar);assert.equal(cal.status,201);const calId=(await cal.json() as any).data.id;
 assert.equal((await req('POST','/api/calendars',{...calendar,name:'Duplicate'})).status,409);
 const clock=await req('GET',`/api/calendars/${calId}/clock`);assert.equal(clock.status,200);assert.equal((await clock.json() as any).data.timezone,'Asia/Makassar');
 assert.equal((await req('POST',`/api/branches/${id}/archive`,{},'MANAGEMENT',2)).status,409);
 assert.equal((await req('POST',`/api/calendars/${calId}/archive`,{},'MANAGEMENT',1)).status,200);
 sqlite.prepare("INSERT INTO branch(id,organization_id,name,timezone) VALUES('foreign','other','Foreign','Asia/Jakarta')").run();
 assert.equal((await req('GET','/api/branches/foreign')).status,404);
 assert.equal((await req('PUT','/api/branches/foreign',input,'MANAGEMENT',1)).status,404);
 const audit=sqlite.prepare('SELECT occurred_at,actor_id FROM master_audit').all();assert.ok(audit.every(x=>x.actor_id==='mg'&&String(x.occurred_at).endsWith('Z')));
 sqlite.close();
});
test('branch-local clock and working minutes exclude holidays/weekends and respect timezone and end boundary',()=>{
 const calendar={weekdays:[1,2,3,4,5],start_time:'08:00',end_time:'17:00',holidays:['2026-12-25']};
 const instant=new Date('2026-10-19T00:00:00Z');
 assert.equal(businessClock(instant,'Asia/Jakarta').time,'07:00');
 assert.equal(isWorkingInstant(instant,'Asia/Jakarta',calendar),false);
 assert.equal(isWorkingInstant(instant,'Asia/Makassar',calendar),true);
 assert.equal(isWorkingInstant(new Date('2026-10-19T10:00:00Z'),'Asia/Jakarta',calendar),false);
 assert.equal(isWorkingInstant(new Date('2026-12-25T02:00:00Z'),'Asia/Jakarta',calendar),false);
 assert.equal(workingMinutesBetween(new Date('2026-10-19T00:00Z'),new Date('2026-10-19T03:00Z'),'Asia/Jakarta',calendar),120);
 assert.equal(workingMinutesBetween(new Date('2026-10-17T02:00Z'),new Date('2026-10-17T03:00Z'),'Asia/Jakarta',calendar),0);
});
